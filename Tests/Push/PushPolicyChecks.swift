import Foundation
@main struct Checks {
 static func main() {
  let owner = PushIdentity(userUID: "u", tenantID: "t", sessionID: UUID())
  func check(_ value: @autoclosure () -> Bool, _ name: String) { precondition(value(), name) }
  check(PushDestination.parse(["jumpType":"chat", "chatType":0, "sessionId":"p"]) == .chat(id:"p", group:false), "single")
  check(PushDestination.parse(["jumpType":"chat", "chatType":1, "sessionId":"g"]) == .chat(id:"g", group:true), "group")
  check(PushDestination.parse(["jumpType":"chat", "chatType":99, "sessionId":"g"]) == nil, "reject unknown")
  check(PushDestination.parse(["jumpType":"chat", "chatType":true, "sessionId":"g"]) == nil, "reject bool")
  check(PushDestination.parse(["jumpType":"chat", "chatType":0, "sessionId":" "]) == nil, "reject empty")
  check(PushDestination.parse(["jumpType":"friend"]) == .friends, "friend")
  check(PushPreferences.decode(["isNewMsgNotify":1,"isVoiceNotice":0,"isShakeNotice":1]) == PushPreferences(enabled:true,sound:false,vibration:true), "prefs")
  check(PushPreferences.decode(["isNewMsgNotify":1]) == nil, "partial invalid")
  check(PushPreferences.saveAccepted(NSNumber(value:true)), "save acknowledged")
  check(!PushPreferences.saveAccepted(NSNumber(value:false)), "server false is not success")
  check(!PushPreferences.saveAccepted(nil), "missing acknowledgement is not success")
  check(PushPayload(info:["jumpType":"friend","recipientUID":42]) == nil, "malformed recipient rejected")
  check(PushPayload(info:["jumpType":"friend","tenantID":""]) == nil, "empty tenant rejected")
  let local = PushPayload(destination:.friends,userUID:"u",tenantID:"t",processID:PushProcess.id,sessionID:UUID())
  check(!local.matches(owner), "late local notification rejects previous run in same process")
  let cold = PushPayload(destination:.friends,userUID:"u",tenantID:"t",processID:UUID(),sessionID:UUID())
  check(cold.matches(owner), "cold process can restore same account notification")
  check(PushMessageSummary.mention(title:"甲",text:"@乙 你好",targets:["b"],userUID:"u") == "@乙 你好", "other mentions retain body")
  check(PushMessageSummary.mention(title:"甲",text:"原文",targets:["u","b"],userUID:"u") == "甲@了你", "later target cannot erase mention")
  check(!PushMessageSummary.allowsGroupNotice(informStatus:0), "closed group notices suppressed")
  check(PushMessageSummary.allowsGroupNotice(informStatus:1), "enabled group notices allowed")
  var policy = PushDeliveryPolicy()
  let event = PushEvent(id:"m", destination:.chat(id:"p",group:false), title:"好友", body:"内容", muted:false, fromSelf:false)
  check(policy.accept(event, preferences:.init(), foreground:true, visible:nil), "first")
  check(!policy.accept(event, preferences:.init(), foreground:false, visible:nil), "duplicate")
  policy.reset()
  check(!policy.accept(event, preferences:.init(enabled:false), foreground:false, visible:nil), "disabled")
  check(!policy.accept(event, preferences:.init(), foreground:true, visible:event.destination), "visible")
  check(PushPayload(destination:.friends, userUID:"u",tenantID:"t").matches(owner), "owner")
  check(!PushPayload(destination:.friends, userUID:"x",tenantID:"t").matches(owner), "other user")
  check(!PushPayload(destination:.friends, userUID:"u",tenantID:"x").matches(owner), "other tenant")
  policy.reset()
  let invite = PushEvent(id:"pairHash",destination:.friends,title:"甲",body:"申请",muted:false,fromSelf:false)
  check(policy.accept(invite,preferences:.init(),foreground:false,visible:nil,now:10), "first friend invite")
  check(!policy.accept(invite,preferences:.init(),foreground:false,visible:nil,now:10.2), "friend duplicate burst")
  check(policy.accept(invite,preferences:.init(),foreground:false,visible:nil,now:20), "later application with same pair hash can alert")
  print("Push policy: 29 checks passed")
 }
}
